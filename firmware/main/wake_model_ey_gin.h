        float s2 = (t_feats[9 * 64 + c] + t_feats[10 * 64 + c] + t_feats[11 * 64 + c] +
                    t_feats[12 * 64 + c] + t_feats[13 * 64 + c] + t_feats[14 * 64 + c]) * (1.0f / 6.0f);
